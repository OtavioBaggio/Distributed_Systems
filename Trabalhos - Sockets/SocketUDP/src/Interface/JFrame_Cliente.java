    private void criaClientSocket() {
        try {
            //cria um socket datagrama para enviar e receber dados
            socket = new DatagramSocket();
        } catch (SocketException ex) {
            ex.printStackTrace();
        }
    }
    
    //chamado pela thread Escutador; invokeLater atualiza a tela com segurança
    public void mostrarMensagem(final String mensagem) {
        SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                txtMensagens.append(mensagem + "\n");
            }
        });
    }

    private void enviar(String mensagem) {
        DatagramPacket pacote = ComunicadorUDP.montaMensagem(mensagem, "localhost", 1234);
        ComunicadorUDP.enviaMensagem(socket, pacote);
    }


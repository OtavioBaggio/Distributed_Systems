    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText().trim();
        String email = txtEmailCadastro.getText().trim();
        if (nome.isEmpty() || email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha nome e email");
            return;
        }
        enviar("CADASTRO;" + nome + ";" + email);
        txtNome.setText("");
        txtEmailCadastro.setText("");
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnSolicitarTokenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSolicitarTokenActionPerformed
        String email = txtEmailToken.getText().trim();
        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o email");
            return;
        }
        enviar("TOKEN;" + email);
    }//GEN-LAST:event_btnSolicitarTokenActionPerformed


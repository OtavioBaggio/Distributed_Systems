    private void btn_conectarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_conectarActionPerformed
        String host = txt_host.getText().trim();

        if (host.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o endereço do servidor!", "campo vazio", JOptionPane.WARNING_MESSAGE);
            txt_host.requestFocus();
            return;
        }

        String HOST_URL = "rmi://" + host + "/ConsultaSessao";
        try {
            interfaceRemota = (IConsultaSessao) Naming.lookup(HOST_URL);

            lbl_numerosCarregados.setText(String.valueOf(interfaceRemota.totalSessoes()));
            lbl_status.setText("Conectado a " + host);
            lbl_status.setForeground(new java.awt.Color(0, 128, 0));

            JOptionPane.showMessageDialog(this,
                    "Conectado ao servidor!\n" + lbl_numerosCarregados.getText() + " registros disponíveis.",
                    "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            txt_numero.requestFocus();
        } catch (Exception e) {
            interfaceRemota = null;
            lbl_numerosCarregados.setText("0");
            lbl_status.setText("Desconectado");
            lbl_status.setForeground(java.awt.Color.RED);
            JOptionPane.showMessageDialog(this,
                    "Erro de conexão com " + HOST_URL + "\nVerifique se o servidor está rodando.\n\n" + e,
                    "Erro de conexão", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_conectarActionPerformed


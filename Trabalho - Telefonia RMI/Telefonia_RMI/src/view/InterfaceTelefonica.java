    private void btn_buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscarActionPerformed
        String numeroCelular = txt_numero.getText().trim();

        //requestFocus é muito brabo, ele já coloca o cursor ja no campo, sem o usuário precisar clicar
        if (numeroCelular.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor digite um número de celular!", "campo vazio", JOptionPane.WARNING_MESSAGE);
            txt_numero.requestFocus();
            return;
        }

        if (interfaceRemota == null) {
            JOptionPane.showMessageDialog(this, "Você não está conectado ao servidor!\nClique em Conectar primeiro.",
                    "Sem conexão", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // pergunta ao servidor quantas sessões ele tem (equivale ao sessoes.isEmpty() da versão local)
            int total = interfaceRemota.totalSessoes();
            lbl_numerosCarregados.setText(String.valueOf(total));
            if (total == 0) {
                JOptionPane.showMessageDialog(this, "Nenhuma sessão carregada no servidor!\nVerifique o arquivo de sessões do servidor.",
                        "Lista vazia", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // a busca no HashMap acontece no servidor; aqui chegam só os dados da sessão (ou null)
            String dadosSessao = interfaceRemota.consultaSessao(numeroCelular);

            if (dadosSessao != null) {
                //Formata os dados para exibição
                String resultado = "[OK] SESSÃO ENCONTRADA\n";
                resultado += "=========================================\n\n";
                resultado += "Número de Celular: " + numeroCelular + "\n\n";
                resultado += "Dados da Sessão:\n";
                resultado += formatarJSON(dadosSessao);

                txtA_resultados.setText(resultado);
            } else {
                String resultado = "[FALHA] SESSÃO NÃO ENCONTRADA\n\n";
                resultado += "O número " + numeroCelular + " não foi encontrado na base de dados.\n";
                resultado += "Verifique se o número está correto e tente novamente.";

                txtA_resultados.setText(resultado);
            }
            txtA_resultados.setCaretPosition(0);
        } catch (java.rmi.RemoteException ex) {
            // servidor caiu ou a rede falhou no meio do caminho
            interfaceRemota = null;
            lbl_status.setText("Desconectado");
            lbl_status.setForeground(java.awt.Color.RED);
            JOptionPane.showMessageDialog(this,
                    "A conexão com o servidor foi perdida.\nClique em Conectar para tentar novamente.\n\n" + ex.getMessage(),
                    "Erro de comunicação", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_buscarActionPerformed

